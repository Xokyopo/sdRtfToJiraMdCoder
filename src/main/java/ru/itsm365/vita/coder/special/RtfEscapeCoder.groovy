    @Override
    String toRtf(String s) {
        String result = s;
        for (Map.Entry<String, String> entry : mapHtmlToMd.entrySet()) {
            result = result.replaceAll(entry.getValue(), entry.getKey());
        }
        return result;
    }

    @Override
    String toMd(String s) {
        String result = s;
        for (Map.Entry<String, String> entry : mapHtmlToMd.entrySet()) {
            result = result.replaceAll(entry.getKey(), entry.getValue());
        }
        return result;
    }
